USE rapido_db;


-- Q1. Find total completed rides in each city.

SELECT 
    city_name,
    (
        SELECT COUNT(*)
        FROM rides r
        WHERE r.city_id = c.city_id
          AND r.ride_status = 'Completed'
    ) AS completed_rides
FROM cities c
ORDER BY completed_rides DESC;

-- Q2. Which city has the highest number of cancelled rides.
SELECT 
    city_id,
    COUNT(*) AS cancelled_rides
FROM rides
WHERE ride_status = 'Cancelled'
GROUP BY city_id
ORDER BY cancelled_rides DESC
LIMIT 1;

-- Q3. Which captain has the highest rating?
SELECT 
    captain_id,
    full_name,
    avg_rating
FROM captains
ORDER BY avg_rating DESC
LIMIT 1;

-- Q4. Find high-performing captains:
-- completed more than 50 rides,
-- rating above 4.5
SELECT 
    captain_id,
    full_name,
    total_rides_completed,
    avg_rating
FROM captains
WHERE total_rides_completed > 50
  AND avg_rating > 4.5
ORDER BY avg_rating DESC;


-- Q5. Find the total number of rides for each vehicle type.

SELECT 
    vt.type_name AS vehicle_type,
    COUNT(r.ride_id) AS total_rides
FROM vehicle_types vt
JOIN rides r
    ON vt.vehicle_type_id = r.vehicle_type_id
GROUP BY vt.type_name
ORDER BY total_rides DESC;

-- Q6. Find total revenue generated by each vehicle type.

SELECT 
    vt.type_name AS vehicle_type,
    SUM(r.fare_amount) AS total_revenue
FROM vehicle_types vt
JOIN rides r
    ON vt.vehicle_type_id = r.vehicle_type_id
WHERE r.ride_status = 'Completed'
GROUP BY vt.type_name
ORDER BY total_revenue DESC;


-- Q7. Find cities having more than 1,000 completed rides.

SELECT 
    c.city_name,
    COUNT(r.ride_id) AS completed_rides
FROM cities c
JOIN rides r
    ON c.city_id = r.city_id
WHERE r.ride_status = 'Completed'
GROUP BY c.city_name
HAVING COUNT(r.ride_id) > 1000
ORDER BY completed_rides DESC;


-- Q8. Find captains who completed more than 50 rides.

SELECT 
    ca.captain_id,
    ca.full_name AS captain_name,
    COUNT(r.ride_id) AS completed_rides
FROM captains ca
JOIN rides r
    ON ca.captain_id = r.captain_id
WHERE r.ride_status = 'Completed'
GROUP BY ca.captain_id, ca.full_name
HAVING COUNT(r.ride_id) > 50
ORDER BY completed_rides DESC;


-- Q9. Find customers who completed more than 20 rides.

SELECT 
    cu.customer_id,
    cu.full_name AS customer_name,
    COUNT(r.ride_id) AS completed_rides
FROM customers cu
JOIN rides r
    ON cu.customer_id = r.customer_id
WHERE r.ride_status = 'Completed'
GROUP BY cu.customer_id, cu.full_name
HAVING COUNT(r.ride_id) > 20
ORDER BY completed_rides DESC;


-- Q10. Find the average fare for each vehicle type.

SELECT 
    vt.type_name AS vehicle_type,
    ROUND(AVG(r.fare_amount), 2) AS average_fare
FROM vehicle_types vt
JOIN rides r
    ON vt.vehicle_type_id = r.vehicle_type_id
WHERE r.ride_status = 'Completed'
GROUP BY vt.type_name
ORDER BY average_fare DESC;




-- Q11. Find cities where average fare is greater than ₹150.

SELECT 
    c.city_name,
    ROUND(AVG(r.fare_amount), 2) AS average_fare
FROM cities c
JOIN rides r
    ON c.city_id = r.city_id
WHERE r.ride_status = 'Completed'
GROUP BY c.city_name
HAVING AVG(r.fare_amount) > 150
ORDER BY average_fare DESC;


-- Q12. Find cities whose revenue is greater than
-- the average city revenue.

SELECT 
    c.city_name,
    SUM(r.fare_amount) AS total_revenue
FROM cities c
JOIN rides r
    ON c.city_id = r.city_id
WHERE r.ride_status = 'Completed'
GROUP BY c.city_id, c.city_name
HAVING SUM(r.fare_amount) > (

    SELECT AVG(city_revenue)
    FROM (
        SELECT 
            city_id,
            SUM(fare_amount) AS city_revenue
        FROM rides
        WHERE ride_status = 'Completed'
        GROUP BY city_id
    ) AS city_data

)
ORDER BY total_revenue DESC;


-- Q13. Find captains having a rating higher than
-- the average captain rating.

SELECT 
    captain_id,
    full_name AS captain_name,
    avg_rating
FROM captains
WHERE avg_rating > (
    SELECT AVG(avg_rating)
    FROM captains
)
ORDER BY avg_rating DESC;


-- Q14. Find the top 3 captains in each city
-- based on completed ride revenue.

SELECT *
FROM (
    SELECT 
        c.city_name,
        ca.full_name AS captain_name,
        SUM(r.fare_amount) AS total_revenue,

        DENSE_RANK() OVER (
            PARTITION BY c.city_id
            ORDER BY SUM(r.fare_amount) DESC
        ) AS captain_rank

    FROM cities c
    JOIN captains ca
        ON c.city_id = ca.city_id
    JOIN rides r
        ON ca.captain_id = r.captain_id

    WHERE r.ride_status = 'Completed'
     GROUP BY 
        c.city_id,
        c.city_name,
        ca.captain_id,
        ca.full_name
) AS ranked_captains

WHERE captain_rank <= 3
ORDER BY city_name, captain_rank;


